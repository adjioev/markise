//! CSS for the styled HTML export, generated from the native theme model.
//!
//! Themes are native ([`Theme`]); the exported page is styled by a stylesheet derived from the
//! active theme's slots and targeted at the spec 03 DOM contract (`#write`, `.md-fences`,
//! `.md-alert-*`, `.cm-s-inner .cm-*` token classes, …), so the file looks like the editor.
//! Print hooks (spec 03 §6): a `@media print` block drops the page background and column limit,
//! and `[data-breakpage]` headings start a new page.

use std::fmt::Write as _;

use markise_theme::{BoxStyle, Rgba, TextAlign, Theme, TokenKind};

/// Default proportional and monospace stacks when the theme names none.
pub const DEFAULT_BODY_STACK: &str =
    "system-ui, -apple-system, \"Segoe UI\", Roboto, \"Helvetica Neue\", Arial, \"Noto Sans\", sans-serif";
pub const DEFAULT_MONO_STACK: &str = "ui-monospace, \"SF Mono\", Menlo, Consolas, \"Liberation Mono\", monospace";

/// CSS color of `c` (`#rrggbb` or `rgba(…)`).
pub fn color(c: Rgba) -> String {
    let [r, g, b, a] = c.0;
    if a == 255 {
        format!("#{r:02x}{g:02x}{b:02x}")
    } else {
        format!("rgba({r},{g},{b},{:.3})", a as f32 / 255.0)
    }
}

fn stack(families: &[String], default: &str) -> String {
    if families.is_empty() {
        return default.to_string();
    }
    families
        .iter()
        .map(|f| {
            let generic = matches!(
                f.as_str(),
                "serif" | "sans-serif" | "monospace" | "cursive" | "fantasy" | "system-ui" | "ui-monospace"
            );
            let plain = f.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
            if generic || (plain && !f.is_empty() && !f.starts_with(|c: char| c.is_ascii_digit())) {
                f.clone()
            } else {
                css_string(f)
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// A CSS string literal: `"` and `\\` escaped, control characters and `<` as hex escapes (so the
/// value can never end a `<style>` element or the string).
pub fn css_string(v: &str) -> String {
    let mut s = String::with_capacity(v.len() + 2);
    s.push('"');
    for c in v.chars() {
        match c {
            '"' => s.push_str("\\\""),
            '\\' => s.push_str("\\\\"),
            '<' | '>' => {
                let _ = write!(s, "\\{:x} ", c as u32);
            }
            c if c.is_control() => {
                let _ = write!(s, "\\{:x} ", c as u32);
            }
            c => s.push(c),
        }
    }
    s.push('"');
    s
}

/// Text for a CSS comment: no comment terminator, no `<`.
fn comment_text(v: &str) -> String {
    v.replace("*/", "* /").replace(['<', '>'], " ")
}

fn box_css(b: &BoxStyle) -> String {
    let mut s = format!(
        "background: {}; color: {}; padding: {}px; border-radius: {}px;",
        color(b.background),
        color(b.text),
        b.padding,
        b.radius
    );
    match b.border {
        Some(c) => {
            let _ = write!(s, " border: 1px solid {};", color(c));
        }
        None => s.push_str(" border: none;"),
    }
    s
}

/// The export stylesheet of `theme`.
pub fn theme_css(theme: &Theme) -> String {
    let t = theme;
    let body = stack(&t.fonts.body, DEFAULT_BODY_STACK);
    let heading = if t.fonts.heading.is_empty() {
        body.clone()
    } else {
        stack(&t.fonts.heading, DEFAULT_BODY_STACK)
    };
    let mono = stack(&t.fonts.mono, DEFAULT_MONO_STACK);
    let mut c = String::with_capacity(6 * 1024);
    let _ = writeln!(
        c,
        "/* Generated by Markise from the native theme \"{}\". */",
        comment_text(&t.name)
    );
    let _ = writeln!(
        c,
        ":root {{ --bg-color: {bg}; --text-color: {fg}; --primary-color: {acc}; --monospace: {mono}; }}",
        bg = color(t.page_bg),
        fg = color(t.text),
        acc = color(t.chrome.accent),
    );
    let _ = writeln!(c, "html {{ font-size: {}px; }}", t.font_size);
    let _ = writeln!(
        c,
        "body {{ margin: 0; background: {}; color: {}; }}",
        color(t.page_bg),
        color(t.text)
    );
    let align = match t.text_align {
        TextAlign::Start => "start",
        TextAlign::Center => "center",
        TextAlign::End => "end",
        TextAlign::Justify => "justify",
    };
    let _ = writeln!(
        c,
        "#write {{ max-width: {}px; margin: 0 auto; padding: {}px {}px; font-family: {body}; line-height: {}; text-align: {align}; box-sizing: border-box; }}",
        t.column_max_width + 2.0 * t.column_padding_x,
        t.column_padding_y,
        t.column_padding_x,
        t.line_height
    );
    let _ = writeln!(
        c,
        "#write p, #write ul, #write ol, #write blockquote, #write pre, #write figure, #write .md-alert {{ margin: 0 0 {}px 0; }}",
        t.block_spacing
    );
    for (i, h) in t.headings.iter().enumerate() {
        let d = &t.heading_decor[i];
        let n = i + 1;
        let _ = write!(
            c,
            "#write h{n} {{ font-family: {heading}; font-size: {}px; color: {}; font-weight: {}; margin: {}px 0 {}px 0; line-height: 1.3;",
            h.size,
            color(h.color),
            if h.bold { 700 } else { 400 },
            h.margin_top,
            h.margin_bottom
        );
        if let Some(r) = h.rule {
            let _ = write!(c, " border-bottom: 1px solid {}; padding-bottom: 0.25em;", color(r));
        }
        if d.italic {
            c.push_str(" font-style: italic;");
        }
        if d.letter_spacing != 0.0 {
            let _ = write!(c, " letter-spacing: {}px;", d.letter_spacing);
        }
        if let Some(bg) = d.background {
            let _ = write!(c, " background: {};", color(bg));
        }
        if let Some((w, col)) = d.bar {
            let _ = write!(c, " border-left: {w}px solid {}; padding-left: 0.4em;", color(col));
        }
        c.push_str(" }\n");
    }
    let _ = writeln!(
        c,
        "#write a {{ color: {}; text-decoration: {}; }}",
        color(t.link),
        if t.link_underline { "underline" } else { "none" }
    );
    let _ = writeln!(c, "#write a:hover {{ text-decoration: underline; }}");
    if let Some(s) = t.inline.strong {
        let _ = writeln!(c, "#write strong {{ color: {}; }}", color(s));
    }
    if let Some(s) = t.inline.em {
        let _ = writeln!(c, "#write em {{ color: {}; }}", color(s));
    }
    if let Some(s) = t.inline.del {
        let _ = writeln!(c, "#write del {{ color: {}; }}", color(s));
    }
    let _ = writeln!(
        c,
        "#write mark {{ background: {}; color: {}; padding: 0 2px; }}",
        color(t.highlight_bg),
        color(t.inline.mark_text.unwrap_or(t.text))
    );
    let ic = &t.inline_code;
    let _ = writeln!(
        c,
        "#write code {{ font-family: var(--monospace); font-size: {:.3}em; background: {}; color: {}; padding: 0 {}px; border-radius: {}px; }}",
        t.mono_scale,
        color(ic.background),
        color(ic.text),
        ic.padding + 1.0,
        ic.radius
    );
    let _ = writeln!(
        c,
        "#write pre.md-fences {{ {} font-family: var(--monospace); font-size: {:.3}em; line-height: 1.5; overflow-x: auto; white-space: pre; }}",
        box_css(&t.code_block),
        t.mono_scale
    );
    let _ = writeln!(
        c,
        "#write pre.md-fences code {{ background: none; color: inherit; padding: 0; font-size: 1em; border-radius: 0; }}"
    );
    let _ = writeln!(
        c,
        "#write .md-math-block, #write .md-diagram-panel, #write pre.md-diagram {{ {} font-family: var(--monospace); white-space: pre-wrap; }}",
        box_css(&t.math_block)
    );
    let _ = writeln!(
        c,
        "#write .md-inline-math {{ font-family: var(--monospace); color: {}; }}",
        color(t.math_block.text)
    );
    let _ = writeln!(
        c,
        "#write pre.md-meta-block {{ {} white-space: pre-wrap; }}",
        box_css(&t.meta_block)
    );
    let _ = writeln!(
        c,
        "#write blockquote {{ border-left: {}px solid {}; padding: 0 0 0 {}px; margin-left: 0; color: {}; background: {};{} }}",
        t.quote_bar_width,
        color(t.quote_bar),
        t.quote_indent,
        color(t.quote_text),
        color(t.quote_bg),
        if t.quote_italic { " font-style: italic;" } else { "" }
    );
    let _ = writeln!(c, "#write ul, #write ol {{ padding-left: {}px; }}", t.list_indent);
    let _ = writeln!(c, "#write li::marker {{ color: {}; }}", color(t.list_marker));
    let _ = writeln!(c, "#write li > p {{ margin: 0 0 0.3em 0; }}");
    let _ = writeln!(c, "#write .md-task-list-item {{ list-style: none; }}");
    let _ = writeln!(
        c,
        "#write .md-task-list-item > input {{ margin-left: -1.3em; accent-color: {}; }}",
        color(t.checkbox_checked)
    );
    let _ = writeln!(
        c,
        "#write hr {{ border: none; border-top: 1px solid {}; margin: 1.2em 0; }}",
        color(t.rule)
    );
    let _ = writeln!(c, "#write table {{ border-collapse: collapse; }}");
    let _ = writeln!(
        c,
        "#write th, #write td {{ border: 1px solid {}; padding: {}px {}px; }}",
        color(t.table_border),
        t.table_cell_padding * 0.6,
        t.table_cell_padding
    );
    let _ = writeln!(c, "#write th {{ background: {}; }}", color(t.table_header_bg));
    let _ = writeln!(
        c,
        "#write tbody tr:nth-child(2n) {{ background: {}; }}",
        color(t.table_stripe_bg)
    );
    let _ = writeln!(c, "#write img {{ max-width: 100%; }}");
    let kinds = ["note", "tip", "important", "warning", "caution"];
    for (k, col) in kinds.iter().zip(t.alert.iter()) {
        let _ = writeln!(
            c,
            "#write .md-alert-{k} {{ border-left: 4px solid {col}; padding-left: 1em; }} #write .md-alert-text-{k} {{ color: {col}; font-weight: 600; }}",
            col = color(*col)
        );
    }
    let _ = writeln!(
        c,
        "#write .footnotes-area {{ color: {}; font-size: 0.9em; }}",
        color(t.meta_text)
    );
    let _ = writeln!(c, "#write .md-toc-item {{ display: block; }}");
    for lvl in 2..=6 {
        let _ = writeln!(
            c,
            "#write .md-toc-h{lvl} {{ margin-left: {}em; }}",
            (lvl - 1) as f32 * 1.2
        );
    }
    // Code token classes (spec 03 §4.5).
    for k in TokenKind::ALL {
        let look = t.token_look(k);
        if look.is_plain() {
            continue;
        }
        let _ = write!(c, ".cm-s-inner .{} {{", k.cm_class());
        if let Some(col) = look.color {
            let _ = write!(c, " color: {};", color(col));
        }
        if look.bold {
            c.push_str(" font-weight: bold;");
        }
        if look.italic {
            c.push_str(" font-style: italic;");
        }
        c.push_str(" }\n");
    }
    c.push_str(
        "@media print {\n  body { background: #fff; }\n  #write { max-width: none; padding: 0; }\n  #write pre.md-fences { white-space: pre-wrap; }\n  [data-breakpage] { page-break-before: always; }\n}\n",
    );
    c
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn css_covers_contract_selectors() {
        let css = theme_css(&Theme::light());
        for sel in [
            "#write {",
            "#write h1 {",
            "#write h6 {",
            "#write pre.md-fences {",
            "#write blockquote {",
            "#write th, #write td {",
            ".md-alert-warning",
            ".cm-s-inner .cm-keyword {",
            "@media print",
            "--bg-color: #fcfcfa",
        ] {
            assert!(css.contains(sel), "missing {sel}");
        }
        assert!(css.contains(&format!("color: {};", color(Theme::light().syntax.keyword))));
    }

    // Codex review P1: hostile theme names / font families cannot leave the stylesheet.
    #[test]
    fn hostile_font_names_and_theme_name_are_escaped() {
        let mut t = Theme::light();
        t.name = "x */ </style><script>a()</script>".into();
        t.fonts.body = vec!["Evil\" </style><script>b()</script>".into(), "serif".into()];
        let css = theme_css(&t);
        assert!(!css.contains('<'), "{css}");
        assert!(!css.contains("*/ <") && css.matches("*/").count() == 1, "{css}");
        assert!(
            css.contains("\"Evil\\\" \\3c /style\\3e \\3c script\\3e b()\\3c /script\\3e \""),
            "{css}"
        );
        let html = crate::render_document(
            &markise_md::parse("x\n"),
            &crate::HtmlOptions {
                css: Some(css),
                ..Default::default()
            },
        );
        assert_eq!(html.to_ascii_lowercase().matches("</style").count(), 1);
    }

    #[test]
    fn colors_and_stacks() {
        assert_eq!(color(Rgba::hex(0x102030)), "#102030");
        assert_eq!(color(Rgba([1, 2, 3, 0])), "rgba(1,2,3,0.000)");
        assert_eq!(
            stack(&["Iowan Old Style".into(), "serif".into()], ""),
            "\"Iowan Old Style\", serif"
        );
    }
}
